"""
Phase 4: external-model judge for generation-quality metrics —
faithfulness/groundedness, answer relevancy, context recall, and citation
accuracy — used ONLY here, for offline batch eval runs triggered from
kb_admin, never on the citizen-facing chat path.

Default judge is Gemini (eval_judge_provider="gemini", reusing the same
GEMINI_API_KEY already configured for answer_question() itself — zero
incremental cost on the free tier). This is a deliberate, EXPLICITLY
ACCEPTED trade-off, not an oversight: the chatbot's own GENERATION_BACKEND
is also Gemini, so this judge scores answers generated by a model from its
own family. Documented LLM-as-judge research shows models tend to rate
their own family's output more favorably (self-preference bias), which can
inflate these scores relative to how a genuinely independent judge would
grade the same answer — chosen anyway here to keep eval cost at zero.
If a run's generation scores look suspiciously high/uniform, that's the
first thing to suspect; eval_judge_provider="anthropic" (needs
eval_judge_api_key set) is kept as an independent-judge fallback for
exactly that sanity check, at a real but small cost (~$1-2 for a full
120-item run on Claude Sonnet pricing).

Scores are 0.0-1.0, judged strictly against the golden item's
expected_key_facts and the actual retrieved context — not the judge's own
world knowledge, so a technically-true but ungrounded claim still scores
low on faithfulness.
"""

import json
import re
from typing import Any, Optional

from kb_admin.core.config import get_settings

JUDGE_SYSTEM_PROMPT = """You are grading a RAG chatbot's answer for a consulate services knowledge base. \
You are given: the user's question, a list of expected key facts (the ground truth), the context chunks \
the bot actually retrieved, and the bot's generated answer. Score the answer on four dimensions, each \
0.0-1.0, based ONLY on the expected key facts and retrieved context given here -- not your own general \
knowledge about consulates/visas/etc, which may be outdated or wrong for this specific office:

- faithfulness: does every factual claim in the answer trace back to the retrieved context? (1.0 = fully \
grounded, 0.0 = fabricated or contradicts the context)
- answer_relevancy: does the answer actually address the user's question? (1.0 = directly and completely, \
0.0 = off-topic or non-responsive)
- context_recall: of the expected key facts, what fraction does the answer actually cover?
- citation_accuracy: are the answer's bracket citations pointing at context chunks that actually support \
the cited claim? (1.0 if all citations check out or there are none needed, 0.0 if citations are missing \
or point at the wrong content)

If expected_key_facts is empty (this is a "should decline" test case), instead score:
- faithfulness: 1.0 if the answer does NOT fabricate an answer (i.e. it declines or says it lacks \
approved info), 0.0 if it confidently answers anyway
- answer_relevancy: 1.0 if the decline is polite/on-topic, 0.0 otherwise
- context_recall: 1.0 (not applicable, no facts to recall)
- citation_accuracy: 1.0 (not applicable)

Respond with ONLY a JSON object: {"faithfulness": <float>, "answer_relevancy": <float>, \
"context_recall": <float>, "citation_accuracy": <float>, "rationale": "<one sentence>"}"""


class JudgeNotConfigured(Exception):
    pass


def _build_user_prompt(
    query: str,
    expected_key_facts: list[str],
    retrieved_chunks: list[dict[str, Any]],
    answer: str,
) -> str:
    facts_block = "\n".join(f"- {fact}" for fact in expected_key_facts) or "(none — this is a should-decline case)"
    context_block = "\n\n".join(
        f"[{i + 1}] {c.get('chunk_text', '')}" for i, c in enumerate(retrieved_chunks)
    ) or "(no chunks retrieved)"
    return (
        f"Question: {query}\n\n"
        f"Expected key facts:\n{facts_block}\n\n"
        f"Retrieved context:\n{context_block}\n\n"
        f"Bot's answer:\n{answer}"
    )


def _extract_json(text: str) -> dict[str, Any]:
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError(f"judge response did not contain a JSON object: {text!r}")
    return json.loads(match.group(0))


def _score_with_anthropic(settings, user_prompt: str, client: Optional[Any]) -> str:
    if not settings.eval_judge_api_key:
        raise JudgeNotConfigured(
            "eval_judge_provider='anthropic' but EVAL_JUDGE_API_KEY is not set in kb_admin's .env"
        )
    if client is None:
        import anthropic

        client = anthropic.Anthropic(api_key=settings.eval_judge_api_key)
    response = client.messages.create(
        model=settings.eval_judge_model,
        max_tokens=300,
        system=JUDGE_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_prompt}],
    )
    return "".join(block.text for block in response.content if block.type == "text")


def _score_with_gemini(settings, user_prompt: str, client: Optional[Any]) -> str:
    # Reuses the bridged chatbot's own gemini_api_key — when kb_admin runs,
    # app.core.config.get_settings() resolves against kb_admin's own .env
    # (relative env_file lookup against CWD), which already carries a copy
    # of GEMINI_API_KEY/GEMINI_MODEL for exactly this reason (see
    # kb_admin/.env.example). No separate eval_judge_api_key needed.
    from app.core.config import get_settings as get_chatbot_settings

    chatbot_settings = get_chatbot_settings()
    if not chatbot_settings.gemini_api_key:
        raise JudgeNotConfigured(
            "eval_judge_provider='gemini' but GEMINI_API_KEY is not set in kb_admin's .env "
            "(same key answer_question() itself needs for GENERATION_BACKEND=gemini)"
        )

    if client is None:
        from google import genai

        client = genai.Client(api_key=chatbot_settings.gemini_api_key)

    from google.genai import types

    config = types.GenerateContentConfig(
        system_instruction=JUDGE_SYSTEM_PROMPT,
        max_output_tokens=300,
        temperature=0.0,
        thinking_config=types.ThinkingConfig(thinking_budget=0),
    )
    response = client.models.generate_content(
        model=settings.eval_judge_model,
        contents=[{"role": "user", "parts": [{"text": user_prompt}]}],
        config=config,
    )
    return response.text or ""


def score_answer(
    query: str,
    expected_key_facts: list[str],
    retrieved_chunks: list[dict[str, Any]],
    answer: str,
    *,
    client: Optional[Any] = None,
) -> dict[str, Any]:
    """One judge call, scoring one generated answer. Raises JudgeNotConfigured
    if the configured provider's API key isn't set — this is an explicit,
    offline-only eval step, not something that should silently no-op and
    report fake scores."""
    settings = get_settings()
    user_prompt = _build_user_prompt(query, expected_key_facts, retrieved_chunks, answer)

    if settings.eval_judge_provider == "gemini":
        text = _score_with_gemini(settings, user_prompt, client)
    elif settings.eval_judge_provider == "anthropic":
        text = _score_with_anthropic(settings, user_prompt, client)
    else:
        raise JudgeNotConfigured(
            f"eval_judge_provider={settings.eval_judge_provider!r} is not supported — use 'gemini' or 'anthropic'"
        )

    return _extract_json(text)
